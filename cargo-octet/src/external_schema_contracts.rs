const CONTRACT_PATH: &str = "standards/external-schemas/contracts/generated.ncl";
const INDEX_PATH: &str = "standards/external-schemas/index.ncl";
const MANIFEST_PATH: &str = "standards/external-schemas/manifest.json";
const MANIFEST_SCHEMA_VERSION: &str = "octet-external-schema-contract-manifest/v1";
const GENERATOR_ID: &str = "cargo-octet.external-schema-contracts/v1";
const GENERATION_COMMAND: &str = "nix develop -c cargo test -p cargo-octet external_schema_contracts";
const JSON_SCHEMA_DRAFT_2020_12: &str = "https://json-schema.org/draft/2020-12/schema";
const CARGO_DENY_SCHEMA_PATH: &str = "standards/external-schemas/pinned/cargo-deny-diagnostics-v1.schema.json";
const COVERAGE_SCHEMA_PATH: &str = "standards/external-schemas/pinned/cargo-llvm-cov-summary-v1.schema.json";
const CARGO_DENY_CONTRACT_ID: &str = "cargo-deny-diagnostics-v1";
const COVERAGE_CONTRACT_ID: &str = "cargo-llvm-cov-summary-v1";
const CARGO_DENY_CONTRACT_NAME: &str = "CargoDenyReportV1";
const COVERAGE_CONTRACT_NAME: &str = "CoverageBaselineSummaryV1";
const CARGO_DENY_SCHEMA_VERSION: &str = "cargo-deny-diagnostics/v1";
const COVERAGE_SCHEMA_VERSION: &str = "cargo-llvm-cov-summary/v1";
const CARGO_DENY_TOOL_FAMILY: &str = "cargo-deny";
const COVERAGE_TOOL_FAMILY: &str = "cargo-llvm-cov";
const RECORD_CONTRACT_MODE: &str = "record-contract";
const DIALECT_KEYWORD: &str = "$schema";
const ROOT_POINTER: &str = "#";
const TOP_LEVEL_INDENT: usize = 2;
const NESTED_INDENT_STEP: usize = 2;
/// Keywords that only annotate a schema; they impose no validation, so ignoring them is faithful.
const ANNOTATION_KEYWORDS: &[&str] = &["$id", "$comment", "title", "description"];

#[derive(Clone, Debug)]
struct ExternalSchemaSource {
    contract_id: &'static str,
    contract_name: &'static str,
    tool_family: &'static str,
    schema_version: &'static str,
    source_path: &'static str,
    generator_mode: &'static str,
}

/// A pinned schema loaded from the checked-in source path.
#[derive(Clone, Debug)]
struct PinnedSchema {
    source: ExternalSchemaSource,
    text: String,
    document: Value,
}

/// The Nickel contract and metadata derived from one pinned schema.
#[derive(Clone, Debug)]
struct GeneratedSchemaContract {
    source: ExternalSchemaSource,
    dialect: String,
    unsupported_keywords: Vec<String>,
    source_identity: ArtifactIdentity,
    contract: String,
}

#[derive(Debug, Serialize)]
struct ExternalSchemaManifest {
    schema_version: String,
    generator: String,
    generation_command: String,
    contracts: Vec<ExternalSchemaManifestEntry>,
    generated_artifacts: Vec<ArtifactIdentity>,
}

#[derive(Debug, Serialize)]
struct ExternalSchemaManifestEntry {
    contract_id: String,
    tool_family: String,
    schema_version: String,
    schema_dialect: String,
    generator_mode: String,
    unsupported_keywords: Vec<String>,
    source_schema: ArtifactIdentity,
    generated_contract: ArtifactIdentity,
}

#[derive(Clone, Debug, Serialize)]
struct ArtifactIdentity {
    path: String,
    blake3: String,
    bytes: u64,
}

/// Translates a JSON Schema subset into a Nickel contract expression, recording every
/// keyword it cannot represent faithfully so generation can fail closed.
#[derive(Default)]
struct SchemaTranslator {
    unsupported_keywords: Vec<String>,
}

fn generate_contracts(schemas: &[PinnedSchema]) -> Result<Vec<GeneratedSchemaContract>, Vec<String>> {
    let mut diagnostics = Vec::new();
    let mut contracts = Vec::with_capacity(schemas.len());
    for schema in schemas {
        let dialect = schema.document.get(DIALECT_KEYWORD).and_then(Value::as_str);
        let mut translator = SchemaTranslator::default();
        let contract = translator.translate(&schema.document, ROOT_POINTER, TOP_LEVEL_INDENT);
        let schema_diagnostics =
            schema_source_diagnostics(schema.source.contract_id, dialect, &translator.unsupported_keywords);
        if !schema_diagnostics.is_empty() {
            diagnostics.extend(schema_diagnostics);
            continue;
        }
        contracts.push(GeneratedSchemaContract {
            source: schema.source.clone(),
            dialect: dialect.unwrap_or_default().to_owned(),
            unsupported_keywords: translator.unsupported_keywords,
            source_identity: artifact_identity(schema.source.source_path, &schema.text),
            contract,
        });
    }
    if diagnostics.is_empty() {
        Ok(contracts)
    } else {
        Err(diagnostics)
    }
}

fn render_generated_contracts(contracts: &[GeneratedSchemaContract]) -> String {
    let mut rendered = String::new();
    rendered.push_str("# @generated by cargo-octet/src/external_schema_contracts.rs; do not edit by hand.\n");
    rendered.push_str("{\n");
    render_metadata(&mut rendered, contracts);
    for contract in contracts {
        writeln!(rendered, "  {} = {},", contract.source.contract_name, contract.contract).expect("render contract");
    }
    rendered.push_str("}\n");
    rendered
}

fn render_index(contracts: &[GeneratedSchemaContract]) -> String {
    let mut rendered = String::new();
    rendered.push_str("# External schema contract library entry point.\n");
    rendered.push_str("let contracts = import \"contracts/generated.ncl\" in\n");
    rendered.push_str("{\n");
    rendered.push_str("  metadata = contracts.metadata,\n");
    for contract in contracts {
        let name = contract.source.contract_name;
        writeln!(rendered, "  {name} = contracts.{name},").expect("render index entry");
    }
    rendered.push_str("}\n");
    rendered
}

fn render_manifest(contracts: &[GeneratedSchemaContract]) -> String {
    let generated_contract = artifact_identity(CONTRACT_PATH, &render_generated_contracts(contracts));
    let manifest = ExternalSchemaManifest {
        schema_version: MANIFEST_SCHEMA_VERSION.to_owned(),
        generator: GENERATOR_ID.to_owned(),
        generation_command: GENERATION_COMMAND.to_owned(),
        contracts: contracts.iter().map(|contract| manifest_entry(contract, &generated_contract)).collect(),
        generated_artifacts: vec![
            generated_contract.clone(),
            artifact_identity(INDEX_PATH, &render_index(contracts)),
        ],
    };
    let mut rendered = serde_json::to_string_pretty(&manifest).expect("serialize external schema manifest");
    rendered.push('\n');
    rendered
}

fn render_metadata(rendered: &mut String, contracts: &[GeneratedSchemaContract]) {
    rendered.push_str("  metadata = [\n");
    for contract in contracts {
        let source = &contract.source;
        writeln!(rendered, "    {{").expect("render metadata header");
        writeln!(rendered, "      contract_id = {:?},", source.contract_id).expect("render contract id");
        writeln!(rendered, "      tool_family = {:?},", source.tool_family).expect("render tool family");
        writeln!(rendered, "      schema_version = {:?},", source.schema_version).expect("render schema version");
        writeln!(rendered, "      schema_dialect = {:?},", contract.dialect).expect("render schema dialect");
        writeln!(rendered, "      source_schema = {:?},", source.source_path).expect("render source schema");
        writeln!(rendered, "      generator = {GENERATOR_ID:?},").expect("render generator");
        writeln!(rendered, "      generator_mode = {:?},", source.generator_mode).expect("render generator mode");
        rendered.push_str("      unsupported_keywords = [");
        for (index, keyword) in contract.unsupported_keywords.iter().enumerate() {
            if index > 0 {
                rendered.push_str(", ");
            }
            write!(rendered, "{keyword:?}").expect("render unsupported keyword");
        }
        rendered.push_str("],\n");
        rendered.push_str("    },\n");
    }
    rendered.push_str("  ],\n");
}

fn manifest_entry(
    contract: &GeneratedSchemaContract,
    generated_contract: &ArtifactIdentity,
) -> ExternalSchemaManifestEntry {
    let source = &contract.source;
    ExternalSchemaManifestEntry {
        contract_id: source.contract_id.to_owned(),
        tool_family: source.tool_family.to_owned(),
        schema_version: source.schema_version.to_owned(),
        schema_dialect: contract.dialect.clone(),
        generator_mode: source.generator_mode.to_owned(),
        unsupported_keywords: contract.unsupported_keywords.clone(),
        source_schema: contract.source_identity.clone(),
        generated_contract: generated_contract.clone(),
    }
}

fn artifact_identity(path: &str, text: &str) -> ArtifactIdentity {
    ArtifactIdentity {
        path: path.to_owned(),
        blake3: blake3::hash(text.as_bytes()).to_hex().to_string(),
        bytes: u64::try_from(text.len()).expect("artifact text length fits u64"),
    }
}

fn schema_sources() -> Vec<ExternalSchemaSource> {
    vec![
        ExternalSchemaSource {
            contract_id: CARGO_DENY_CONTRACT_ID,
            contract_name: CARGO_DENY_CONTRACT_NAME,
            tool_family: CARGO_DENY_TOOL_FAMILY,
            schema_version: CARGO_DENY_SCHEMA_VERSION,
            source_path: CARGO_DENY_SCHEMA_PATH,
            generator_mode: RECORD_CONTRACT_MODE,
        },
        ExternalSchemaSource {
            contract_id: COVERAGE_CONTRACT_ID,
            contract_name: COVERAGE_CONTRACT_NAME,
            tool_family: COVERAGE_TOOL_FAMILY,
            schema_version: COVERAGE_SCHEMA_VERSION,
            source_path: COVERAGE_SCHEMA_PATH,
            generator_mode: RECORD_CONTRACT_MODE,
        },
    ]
}

fn load_pinned_schemas(repo_root: &Path) -> Vec<PinnedSchema> {
    schema_sources()
        .into_iter()
        .map(|source| {
            let text = std::fs::read_to_string(repo_root.join(source.source_path))
                .unwrap_or_else(|error| panic!("read schema {}: {error}", source.source_path));
            let document = serde_json::from_str(&text)
                .unwrap_or_else(|error| panic!("parse schema {}: {error}", source.source_path));
            PinnedSchema { source, text, document }
        })
        .collect()
}

fn schema_source_diagnostics(contract_id: &str, dialect: Option<&str>, unsupported_keywords: &[String]) -> Vec<String> {
    let mut diagnostics = Vec::new();
    match dialect {
        Some(JSON_SCHEMA_DRAFT_2020_12) => {}
        Some(dialect) => diagnostics.push(format!(
            "unsupported external schema dialect `{dialect}` for `{contract_id}`; expected `{JSON_SCHEMA_DRAFT_2020_12}`"
        )),
        None => diagnostics.push(format!(
            "external schema `{contract_id}` does not declare `{DIALECT_KEYWORD}`; expected `{JSON_SCHEMA_DRAFT_2020_12}`"
        )),
    }
    diagnostics.extend(
        unsupported_keywords
            .iter()
            .map(|keyword| format!("unsupported external schema keyword `{keyword}` for `{contract_id}`")),
    );
    diagnostics
}

impl SchemaTranslator {
    fn translate(&mut self, schema: &Value, pointer: &str, indent: usize) -> String {
        let Some(object) = schema.as_object() else {
            if schema != &Value::Bool(true) {
                self.unsupported(pointer, "boolean schema");
            }
            return "Dyn".to_owned();
        };
        let mut consumed: BTreeSet<&'static str> = ANNOTATION_KEYWORDS.iter().copied().collect();
        if pointer == ROOT_POINTER {
            consumed.insert(DIALECT_KEYWORD);
        }
        let contract = if let Some(value) = object.get("const") {
            consumed.extend(["const", "type"]);
            self.translate_const(value, pointer)
        } else {
            match object.get("type").and_then(Value::as_str) {
                None => "Dyn".to_owned(),
                Some(type_name) => {
                    consumed.insert("type");
                    self.translate_type(type_name, object, &mut consumed, pointer, indent)
                }
            }
        };
        for keyword in object.keys() {
            if !consumed.contains(keyword.as_str()) {
                self.unsupported(pointer, keyword);
            }
        }
        contract
    }

    fn translate_type(
        &mut self,
        type_name: &str,
        object: &Map<String, Value>,
        consumed: &mut BTreeSet<&'static str>,
        pointer: &str,
        indent: usize,
    ) -> String {
        match type_name {
            "object" => {
                consumed.extend(["properties", "required", "additionalProperties"]);
                self.translate_object(object, pointer, indent)
            }
            "array" => {
                consumed.insert("items");
                let items = object.get("items").map_or_else(
                    || "Dyn".to_owned(),
                    |items| self.translate(items, &format!("{pointer}/items"), indent),
                );
                if items.starts_with('{') || !items.contains(' ') {
                    format!("Array {items}")
                } else {
                    format!("Array ({items})")
                }
            }
            "string" => {
                consumed.insert("minLength");
                match object.get("minLength") {
                    None => "String".to_owned(),
                    Some(min_length) => {
                        let Some(min_length) = min_length.as_u64() else {
                            self.unsupported(pointer, "minLength");
                            return "String".to_owned();
                        };
                        predicate(&format!("std.is_string value && std.string.length value >= {min_length}"))
                    }
                }
            }
            "number" | "integer" => {
                consumed.extend(["minimum", "maximum"]);
                let mut conditions = vec!["std.is_number value".to_owned()];
                if type_name == "integer" {
                    conditions.push("std.number.is_integer value".to_owned());
                }
                for (keyword, operator) in [("minimum", ">="), ("maximum", "<=")] {
                    match object.get(keyword) {
                        None => {}
                        Some(Value::Number(bound)) => conditions.push(format!("value {operator} {bound}")),
                        Some(_) => self.unsupported(pointer, keyword),
                    }
                }
                if conditions.len() == 1 && type_name == "number" {
                    "Number".to_owned()
                } else {
                    predicate(&conditions.join(" && "))
                }
            }
            "boolean" => "Bool".to_owned(),
            "null" => predicate("value == null"),
            other => {
                self.unsupported(pointer, &format!("type {other}"));
                "Dyn".to_owned()
            }
        }
    }

    fn translate_object(&mut self, object: &Map<String, Value>, pointer: &str, indent: usize) -> String {
        let empty = Map::new();
        let properties = match object.get("properties") {
            None => &empty,
            Some(Value::Object(properties)) => properties,
            Some(_) => {
                self.unsupported(pointer, "properties");
                &empty
            }
        };
        let required: BTreeSet<&str> = match object.get("required") {
            None => BTreeSet::new(),
            Some(Value::Array(names)) if names.iter().all(Value::is_string) => {
                names.iter().filter_map(Value::as_str).collect()
            }
            Some(_) => {
                self.unsupported(pointer, "required");
                BTreeSet::new()
            }
        };
        let open = match object.get("additionalProperties") {
            None | Some(Value::Bool(true)) => true,
            Some(Value::Bool(false)) => false,
            Some(_) => {
                self.unsupported(pointer, "additionalProperties");
                true
            }
        };
        let field_indent = indent + NESTED_INDENT_STEP;
        let mut names: BTreeSet<&str> = properties.keys().map(String::as_str).collect();
        names.extend(required.iter().copied());
        if names.is_empty() && !open {
            return "{}".to_owned();
        }
        let mut rendered = String::from("{\n");
        for name in names {
            let field_contract = properties.get(name).map_or_else(
                || "Dyn".to_owned(),
                |property| self.translate(property, &format!("{pointer}/properties/{name}"), field_indent),
            );
            let optional = if required.contains(name) { "" } else { " | optional" };
            writeln!(rendered, "{:field_indent$}{} | {field_contract}{optional},", "", field_name(name))
                .expect("render record field");
        }
        if open {
            writeln!(rendered, "{:field_indent$}..", "").expect("render open record marker");
        }
        write!(rendered, "{:indent$}}}", "").expect("render record close");
        rendered
    }

    fn translate_const(&mut self, value: &Value, pointer: &str) -> String {
        let literal = match value {
            Value::Null => "null".to_owned(),
            Value::Bool(value) => value.to_string(),
            Value::Number(value) => value.to_string(),
            Value::String(value) => format!("{value:?}"),
            Value::Array(_) | Value::Object(_) => {
                self.unsupported(pointer, "const");
                return "Dyn".to_owned();
            }
        };
        predicate(&format!("value == {literal}"))
    }

    fn unsupported(&mut self, pointer: &str, keyword: &str) {
        self.unsupported_keywords.push(format!("{pointer}/{keyword}"));
    }
}

fn predicate(condition: &str) -> String {
    format!("std.contract.from_predicate (fun value => {condition})")
}

fn field_name(name: &str) -> String {
    let mut chars = name.chars();
    let is_identifier = chars.next().is_some_and(|first| first == '_' || first.is_ascii_alphabetic())
        && chars.all(|next| next == '_' || next == '-' || next == '\'' || next.is_ascii_alphanumeric());
    if is_identifier {
        name.to_owned()
    } else {
        format!("{name:?}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const VALID_FIXTURES: &[&str] = &[
        "standards/external-schemas/fixtures/valid/dependency_audit_report.ncl",
        "standards/external-schemas/fixtures/valid/dependency_audit_extra_fields.ncl",
        "standards/external-schemas/fixtures/valid/coverage_baseline_summary.ncl",
        "standards/external-schemas/fixtures/valid/coverage_baseline_extra_fields.ncl",
    ];
    const INVALID_FIXTURES: &[&str] = &[
        "standards/external-schemas/fixtures/invalid/dependency_audit_missing_message.ncl",
        "standards/external-schemas/fixtures/invalid/dependency_audit_missing_diagnostics.ncl",
        "standards/external-schemas/fixtures/invalid/dependency_audit_unsupported_version.ncl",
        "standards/external-schemas/fixtures/invalid/dependency_audit_wrong_type.ncl",
        "standards/external-schemas/fixtures/invalid/coverage_percent_out_of_range.ncl",
        "standards/external-schemas/fixtures/invalid/coverage_missing_summary.ncl",
    ];
    const UNSUPPORTED_DIALECT: &str = "https://json-schema.org/draft-04/schema";
    const FIRST_SCHEMA_INDEX: usize = 0;

    #[test]
    fn generated_external_schema_contracts_are_fresh() {
        let repo_root = repo_root();
        let contracts = generated_contracts(&repo_root);
        assert_eq!(read_repo_file(&repo_root, CONTRACT_PATH), render_generated_contracts(&contracts));
        assert_eq!(read_repo_file(&repo_root, INDEX_PATH), render_index(&contracts));
        assert_eq!(read_repo_file(&repo_root, MANIFEST_PATH), render_manifest(&contracts));
    }

    #[test]
    #[ignore = "writes the checked generated external schema contracts, index, and manifest"]
    fn regenerate_external_schema_contracts() {
        let repo_root = repo_root();
        let contracts = generated_contracts(&repo_root);
        for (path, text) in [
            (CONTRACT_PATH, render_generated_contracts(&contracts)),
            (INDEX_PATH, render_index(&contracts)),
            (MANIFEST_PATH, render_manifest(&contracts)),
        ] {
            std::fs::write(repo_root.join(path), text).unwrap_or_else(|error| panic!("write {path}: {error}"));
        }
    }

    #[test]
    fn external_schema_fixtures_accept_valid_and_reject_invalid_reports() {
        let repo_root = repo_root();
        for fixture in VALID_FIXTURES {
            let output = nickel_export(&repo_root, fixture);
            assert!(
                output.status.success(),
                "valid fixture {fixture} should pass: stderr={}",
                String::from_utf8_lossy(&output.stderr)
            );
        }
        for fixture in INVALID_FIXTURES {
            let output = nickel_export(&repo_root, fixture);
            assert!(
                !output.status.success(),
                "invalid fixture {fixture} should fail but stdout was {}",
                String::from_utf8_lossy(&output.stdout)
            );
        }
    }

    #[test]
    fn generated_contract_metadata_reads_dialect_from_pinned_schema() {
        let contracts = generated_contracts(&repo_root());

        assert!(contracts.iter().all(|contract| contract.dialect == JSON_SCHEMA_DRAFT_2020_12));
        assert!(contracts.iter().all(|contract| contract.unsupported_keywords.is_empty()));
    }

    #[test]
    fn unsupported_schema_dialect_is_rejected_before_generation() {
        let mut schemas = load_pinned_schemas(&repo_root());
        let mut schema = schemas.remove(FIRST_SCHEMA_INDEX);
        schema.document[DIALECT_KEYWORD] = Value::from(UNSUPPORTED_DIALECT);

        let diagnostics = generate_contracts(&[schema.clone()]).expect_err("draft-04 dialect must fail closed");
        assert!(diagnostics.iter().any(|diagnostic| diagnostic.contains(UNSUPPORTED_DIALECT)));

        schema.document.as_object_mut().expect("schema object").remove(DIALECT_KEYWORD);
        let diagnostics = generate_contracts(&[schema]).expect_err("missing dialect must fail closed");
        assert!(diagnostics.iter().any(|diagnostic| diagnostic.contains(DIALECT_KEYWORD)));
    }

    #[test]
    fn unsupported_schema_keyword_is_rejected_before_generation() {
        let mut schemas = load_pinned_schemas(&repo_root());
        let mut schema = schemas.remove(FIRST_SCHEMA_INDEX);
        schema.document["properties"]["schema_version"] = serde_json::json!({ "type": "string", "pattern": "^v" });
        schema.document["additionalProperties"] = serde_json::json!({ "type": "string" });

        let diagnostics = generate_contracts(&[schema]).expect_err("unsupported keywords must fail closed");

        assert!(diagnostics.iter().any(|diagnostic| diagnostic.contains("#/properties/schema_version/pattern")));
        assert!(diagnostics.iter().any(|diagnostic| diagnostic.contains("#/additionalProperties")));
    }

    #[test]
    fn translation_maps_required_to_mandatory_and_additional_properties_to_open_records() {
        let schema = serde_json::json!({
            "type": "object",
            "properties": {
                "kept": { "type": "string" },
                "maybe": { "type": "number" },
                "closed": { "type": "object", "additionalProperties": false }
            },
            "required": ["kept"]
        });
        let mut translator = SchemaTranslator::default();

        let contract = translator.translate(&schema, ROOT_POINTER, 0);

        assert!(translator.unsupported_keywords.is_empty());
        assert_eq!(contract, "{\n  closed | {} | optional,\n  kept | String,\n  maybe | Number | optional,\n  ..\n}");
    }

    fn generated_contracts(repo_root: &Path) -> Vec<GeneratedSchemaContract> {
        generate_contracts(&load_pinned_schemas(repo_root))
            .unwrap_or_else(|diagnostics| panic!("external schema generation failed: {diagnostics:?}"))
    }

    fn nickel_export(repo_root: &Path, fixture: &str) -> std::process::Output {
        Command::new("nickel")
            .args(["export", "--format", "json", fixture])
            .current_dir(repo_root)
            .output()
            .unwrap_or_else(|error| panic!("run nickel for {fixture}: {error}"))
    }

    fn read_repo_file(repo_root: &Path, path: &str) -> String {
        std::fs::read_to_string(repo_root.join(path)).unwrap_or_else(|error| panic!("read {path}: {error}"))
    }

    fn repo_root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).parent().expect("repo root").to_path_buf()
    }
}
