use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

use serde::Serialize;

const CONTRACT_PATH: &str = "standards/external-schemas/contracts/generated.ncl";
const INDEX_PATH: &str = "standards/external-schemas/index.ncl";
const MANIFEST_PATH: &str = "standards/external-schemas/manifest.json";
const MANIFEST_SCHEMA_VERSION: &str = "octet-external-schema-contract-manifest/v1";
const GENERATOR_ID: &str = "cargo-octet.external-schema-contracts/v1";
const GENERATION_COMMAND: &str = "nix develop -c cargo test -p cargo-octet external_schema_contracts";
const JSON_SCHEMA_DRAFT_2020_12: &str = "https://json-schema.org/draft/2020-12/schema";
const CARGO_DENY_SCHEMA_PATH: &str = "standards/external-schemas/pinned/cargo-deny-diagnostics-v1.schema.json";
const COVERAGE_SCHEMA_PATH: &str = "standards/external-schemas/pinned/cargo-llvm-cov-summary-v1.schema.json";
const CARGO_DENY_CONTRACT_ID: &str = "cargo-deny-diagnostics-v1";
const COVERAGE_CONTRACT_ID: &str = "cargo-llvm-cov-summary-v1";
const CARGO_DENY_SCHEMA_VERSION: &str = "cargo-deny-diagnostics/v1";
const COVERAGE_SCHEMA_VERSION: &str = "cargo-llvm-cov-summary/v1";
const CARGO_DENY_TOOL_FAMILY: &str = "cargo-deny";
const COVERAGE_TOOL_FAMILY: &str = "cargo-llvm-cov";
const RECORD_CONTRACT_MODE: &str = "record-contract";
const UNSUPPORTED_DIALECT: &str = "https://json-schema.org/draft-04/schema";
const FIRST_SCHEMA_INDEX: usize = 0;

#[derive(Clone, Debug)]
struct ExternalSchemaSource {
    contract_id: &'static str,
    tool_family: &'static str,
    schema_version: &'static str,
    dialect: &'static str,
    source_path: &'static str,
    generator_mode: &'static str,
    unsupported_keywords: &'static [&'static str],
}

#[derive(Debug, Serialize)]
struct ExternalSchemaManifest {
    schema_version: String,
    generator: String,
    generation_command: String,
    contracts: Vec<ExternalSchemaManifestEntry>,
    generated_artifacts: Vec<ArtifactIdentity>,
}

#[derive(Debug, Serialize)]
struct ExternalSchemaManifestEntry {
    contract_id: String,
    tool_family: String,
    schema_version: String,
    schema_dialect: String,
    generator_mode: String,
    unsupported_keywords: Vec<String>,
    source_schema: ArtifactIdentity,
    generated_contract: ArtifactIdentity,
}

#[derive(Clone, Debug, Serialize)]
struct ArtifactIdentity {
    path: String,
    blake3: String,
    bytes: u64,
}

fn render_generated_contracts() -> String {
    let mut rendered = String::new();
    rendered.push_str("# @generated by cargo-octet/src/external_schema_contracts.rs; do not edit by hand.\n");
    rendered.push_str("let NonEmptyString = std.contract.from_predicate (fun value => std.is_string value && std.string.length value > 0) in\n");
    rendered.push_str("let Percent = std.contract.from_predicate (fun value => std.is_number value && value >= 0 && value <= 100) in\n");
    render_exact_string_contract(&mut rendered, "CargoDenySchemaVersion", CARGO_DENY_SCHEMA_VERSION);
    render_exact_string_contract(&mut rendered, "CoverageSchemaVersion", COVERAGE_SCHEMA_VERSION);
    rendered.push_str("let CargoDenyDiagnostic = {\n");
    rendered.push_str("  category | NonEmptyString,\n");
    rendered.push_str("  severity | NonEmptyString,\n");
    rendered.push_str("  message | NonEmptyString,\n");
    rendered.push_str("} in\n");
    rendered.push_str("let CoverageFinding = {\n");
    rendered.push_str("  metric | NonEmptyString,\n");
    rendered.push_str("  message | String | default = \"\",\n");
    rendered.push_str("} in\n");
    rendered.push_str("let CoverageSummary = {\n");
    rendered.push_str("  line_percent | Percent | default = 0,\n");
    rendered.push_str("  branch_percent | Percent | default = 0,\n");
    rendered.push_str("  function_percent | Percent | default = 0,\n");
    rendered.push_str("} in\n");
    rendered.push_str("{\n");
    render_metadata(&mut rendered, &schema_sources());
    rendered.push_str("  CargoDenyReportV1 = {\n");
    rendered.push_str("    schema_version | CargoDenySchemaVersion | default = \"");
    rendered.push_str(CARGO_DENY_SCHEMA_VERSION);
    rendered.push_str("\",\n");
    rendered.push_str("    diagnostics | Array CargoDenyDiagnostic | default = [],\n");
    rendered.push_str("  },\n");
    rendered.push_str("  CoverageBaselineSummaryV1 = {\n");
    rendered.push_str("    schema_version | CoverageSchemaVersion | default = \"");
    rendered.push_str(COVERAGE_SCHEMA_VERSION);
    rendered.push_str("\",\n");
    rendered.push_str("    summary | CoverageSummary,\n");
    rendered.push_str("    regressions | Array CoverageFinding | default = [],\n");
    rendered.push_str("    threshold_failures | Array CoverageFinding | default = [],\n");
    rendered.push_str("  },\n");
    rendered.push_str("}\n");
    rendered
}

fn render_index() -> String {
    "# External schema contract library entry point.\nlet contracts = import \"contracts/generated.ncl\" in\n{\n  metadata = contracts.metadata,\n  CargoDenyReportV1 = contracts.CargoDenyReportV1,\n  CoverageBaselineSummaryV1 = contracts.CoverageBaselineSummaryV1,\n}\n"
        .to_owned()
}

fn render_manifest(repo_root: &Path) -> String {
    let manifest = ExternalSchemaManifest {
        schema_version: MANIFEST_SCHEMA_VERSION.to_owned(),
        generator: GENERATOR_ID.to_owned(),
        generation_command: GENERATION_COMMAND.to_owned(),
        contracts: schema_sources().into_iter().map(|schema| manifest_entry(repo_root, &schema)).collect(),
        generated_artifacts: vec![
            artifact_identity(CONTRACT_PATH, &render_generated_contracts()),
            artifact_identity(INDEX_PATH, &render_index()),
        ],
    };
    let mut rendered = serde_json::to_string_pretty(&manifest).expect("serialize external schema manifest");
    rendered.push('\n');
    rendered
}

fn render_exact_string_contract(rendered: &mut String, name: &str, expected: &str) {
    writeln!(rendered, "let {name} = std.contract.from_predicate (fun value => value == {expected:?}) in")
        .expect("render exact string contract");
}

fn render_metadata(rendered: &mut String, schemas: &[ExternalSchemaSource]) {
    rendered.push_str("  metadata = [\n");
    for schema in schemas {
        writeln!(rendered, "    {{").expect("render metadata header");
        writeln!(rendered, "      contract_id = {:?},", schema.contract_id).expect("render contract id");
        writeln!(rendered, "      tool_family = {:?},", schema.tool_family).expect("render tool family");
        writeln!(rendered, "      schema_version = {:?},", schema.schema_version).expect("render schema version");
        writeln!(rendered, "      schema_dialect = {:?},", schema.dialect).expect("render schema dialect");
        writeln!(rendered, "      source_schema = {:?},", schema.source_path).expect("render source schema");
        writeln!(rendered, "      generator = {:?},", GENERATOR_ID).expect("render generator");
        writeln!(rendered, "      generator_mode = {:?},", schema.generator_mode).expect("render generator mode");
        rendered.push_str("      unsupported_keywords = [");
        for (index, keyword) in schema.unsupported_keywords.iter().enumerate() {
            if index > 0 {
                rendered.push_str(", ");
            }
            write!(rendered, "{keyword:?}").expect("render unsupported keyword");
        }
        rendered.push_str("],\n");
        rendered.push_str("    },\n");
    }
    rendered.push_str("  ],\n");
}

fn manifest_entry(repo_root: &Path, schema: &ExternalSchemaSource) -> ExternalSchemaManifestEntry {
    let source_text = std::fs::read_to_string(repo_root.join(schema.source_path))
        .unwrap_or_else(|error| panic!("read schema {}: {error}", schema.source_path));
    let generated_contract = artifact_identity(CONTRACT_PATH, &render_generated_contracts());
    ExternalSchemaManifestEntry {
        contract_id: schema.contract_id.to_owned(),
        tool_family: schema.tool_family.to_owned(),
        schema_version: schema.schema_version.to_owned(),
        schema_dialect: schema.dialect.to_owned(),
        generator_mode: schema.generator_mode.to_owned(),
        unsupported_keywords: schema.unsupported_keywords.iter().map(|keyword| (*keyword).to_owned()).collect(),
        source_schema: artifact_identity(schema.source_path, &source_text),
        generated_contract,
    }
}

fn artifact_identity(path: &str, text: &str) -> ArtifactIdentity {
    ArtifactIdentity {
        path: path.to_owned(),
        blake3: blake3::hash(text.as_bytes()).to_hex().to_string(),
        bytes: u64::try_from(text.len()).expect("artifact text length fits u64"),
    }
}

fn schema_sources() -> Vec<ExternalSchemaSource> {
    vec![
        ExternalSchemaSource {
            contract_id: CARGO_DENY_CONTRACT_ID,
            tool_family: CARGO_DENY_TOOL_FAMILY,
            schema_version: CARGO_DENY_SCHEMA_VERSION,
            dialect: JSON_SCHEMA_DRAFT_2020_12,
            source_path: CARGO_DENY_SCHEMA_PATH,
            generator_mode: RECORD_CONTRACT_MODE,
            unsupported_keywords: &[],
        },
        ExternalSchemaSource {
            contract_id: COVERAGE_CONTRACT_ID,
            tool_family: COVERAGE_TOOL_FAMILY,
            schema_version: COVERAGE_SCHEMA_VERSION,
            dialect: JSON_SCHEMA_DRAFT_2020_12,
            source_path: COVERAGE_SCHEMA_PATH,
            generator_mode: RECORD_CONTRACT_MODE,
            unsupported_keywords: &[],
        },
    ]
}

fn schema_source_diagnostics(source: &ExternalSchemaSource) -> Vec<String> {
    if source.dialect == JSON_SCHEMA_DRAFT_2020_12 {
        Vec::new()
    } else {
        vec![format!(
            "unsupported external schema dialect `{}` for `{}`; expected `{JSON_SCHEMA_DRAFT_2020_12}`",
            source.dialect, source.contract_id
        )]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const VALID_FIXTURES: &[&str] = &[
        "standards/external-schemas/fixtures/valid/dependency_audit_report.ncl",
        "standards/external-schemas/fixtures/valid/coverage_baseline_summary.ncl",
    ];
    const INVALID_FIXTURES: &[&str] = &[
        "standards/external-schemas/fixtures/invalid/dependency_audit_missing_message.ncl",
        "standards/external-schemas/fixtures/invalid/dependency_audit_unsupported_version.ncl",
        "standards/external-schemas/fixtures/invalid/dependency_audit_wrong_type.ncl",
        "standards/external-schemas/fixtures/invalid/coverage_percent_out_of_range.ncl",
    ];

    #[test]
    fn generated_external_schema_contracts_are_fresh() {
        let repo_root = repo_root();
        assert_eq!(read_repo_file(&repo_root, CONTRACT_PATH), render_generated_contracts());
        assert_eq!(read_repo_file(&repo_root, INDEX_PATH), render_index());
        assert_eq!(read_repo_file(&repo_root, MANIFEST_PATH), render_manifest(&repo_root));
    }

    #[test]
    fn external_schema_fixtures_accept_valid_and_reject_invalid_reports() {
        let repo_root = repo_root();
        for fixture in VALID_FIXTURES {
            let output = nickel_export(&repo_root, fixture);
            assert!(
                output.status.success(),
                "valid fixture {fixture} should pass: stderr={}",
                String::from_utf8_lossy(&output.stderr)
            );
        }
        for fixture in INVALID_FIXTURES {
            let output = nickel_export(&repo_root, fixture);
            assert!(
                !output.status.success(),
                "invalid fixture {fixture} should fail but stdout was {}",
                String::from_utf8_lossy(&output.stdout)
            );
        }
    }

    #[test]
    fn unsupported_schema_dialect_is_rejected_before_generation() {
        let mut schemas = schema_sources();
        let schema = ExternalSchemaSource {
            dialect: UNSUPPORTED_DIALECT,
            ..schemas.remove(FIRST_SCHEMA_INDEX)
        };

        let diagnostics = schema_source_diagnostics(&schema);

        assert!(diagnostics.iter().any(|diagnostic| diagnostic.contains("unsupported external schema dialect")));
    }

    fn nickel_export(repo_root: &Path, fixture: &str) -> std::process::Output {
        Command::new("nickel")
            .args(["export", "--format", "json", fixture])
            .current_dir(repo_root)
            .output()
            .unwrap_or_else(|error| panic!("run nickel for {fixture}: {error}"))
    }

    fn read_repo_file(repo_root: &Path, path: &str) -> String {
        std::fs::read_to_string(repo_root.join(path)).unwrap_or_else(|error| panic!("read {path}: {error}"))
    }

    fn repo_root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).parent().expect("repo root").to_path_buf()
    }
}
