"""Admit only the exact owner-approved RC source/reference tuple to object rails.

This is an offline byte/provenance check, not a signature or correctness proof.
The frozen candidate, owner decision, audit envelope and original producer-source
binding are review inputs, not expected receipts generated by the CLI under check.
"""

