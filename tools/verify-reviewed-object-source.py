#!/usr/bin/env python3
"""Admit only the independently reviewed v2 source/reference bytes to object rails.

This is an offline byte/provenance check, not a signature or correctness proof.
The candidate and reviewed manifest digests are external review anchors rather
than expected values generated by the Object CLI being checked.
"""

import argparse
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path, PurePosixPath

CANDIDATE_PATH = "cargo-octet/tests/fixtures/object-corpus/source-token-v2/candidate-source-manifest.json"
REVIEWED_PATH = "cargo-octet/tests/fixtures/object-corpus/source-token-v2/reviewed-source-manifest.json"
APPROVAL_MANIFEST_PATH = "openspec/changes/source-token-v2-function-object-cutover/evidence/owner-source-bound-references.txt"
APPROVAL_ARCHIVE_PATH = "openspec/changes/archive/2026-10-02-source-token-v2-function-object-cutover/evidence/owner-source-bound-references.txt"
# This in-repository byte lock detects drift; it is not an external owner signature.
APPROVAL_ARCHIVE_B3 = "a86d4c22740d4ea0427285d62133c8434dc77c3d144403902f276031836abcae"
CANDIDATE_B3 = "6d79a8b09c4e7dd20236f4a141c01d6c18b793df7aad93e8ee4ec1d7fb83b221"
REVIEWED_B3 = "2f420d0464e67a8b6ae518e7215eefd1ba8afc47d1849c07afedf284f196da29"
REVISION = "7546a78b4eeef8686c6837e187aa12420f4f03bb"
MODULE_B3 = "11f0f4233aaf3153966f6aa37de570c2dcd0e75335591934461ae2b25ab3ecb1"
NIX_NAR_HASH = "sha256-70AmHxWEbeQK3SFi9ZZ67Prmy3d1zgXHLk/AdPp+EdE="
GIT_URL = "ssh://git@github.com/OnixResearch/valence.git"
REVIEW_REF = "review/source-token-v2-7546a78b"
CARGO_SOURCE = f"git+{GIT_URL}?rev={REVISION}#{REVISION}"
FLAKE_URL = f"git+{GIT_URL}?ref={REVIEW_REF}&rev={REVISION}"
MODULE_PATH = "crates/valence-core/src/function_object.rs"
REFERENCE_COUNTS = [1, 795, 1258, 1258]
REFERENCE_FILES = {
    "positive-v2-receipt.json": "fixed_quoted_url",
    "internal-corpus-receipt.json": "internal_corpus",
    "expanded-internal-corpus-receipt.json": "expanded_internal_corpus",
    "expanded-internal-corpus-caveat-taxonomy.json": "expanded_internal_corpus",
}


class AdmissionError(Exception):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise AdmissionError(message)


def safe_file(root: Path, relative: str) -> Path:
    require(isinstance(relative, str) and relative and "\\" not in relative, f"unsafe path: {relative!r}")
    path = PurePosixPath(relative)
    require(
        not path.is_absolute() and str(path) == relative and all(part not in ("", ".", "..") for part in relative.split("/")),
        f"unsafe path: {relative!r}",
    )
    current = root
    for part in path.parts:
        current = current / part
        require(not current.is_symlink(), f"symlink path: {relative}")
    try:
        resolved = current.resolve(strict=True)
    except (OSError, RuntimeError) as error:
        raise AdmissionError(f"missing path {relative}: {error}") from error
    require(resolved.is_relative_to(root) and resolved.is_file(), f"path escapes root or is not a file: {relative}")
    return resolved


def blake3(path: Path) -> str:
    try:
        output = subprocess.run(["b3sum", "--", str(path)], check=True, capture_output=True, text=True)
    except (OSError, subprocess.CalledProcessError) as error:
        raise AdmissionError(f"cannot BLAKE3 hash {path}: {error}") from error
    return output.stdout.split()[0]


def json_file(path: Path) -> dict:
    try:
        value = json.loads(path.read_bytes())
    except (OSError, ValueError) as error:
        raise AdmissionError(f"invalid JSON {path}: {error}") from error
    require(isinstance(value, dict), f"expected JSON object: {path}")
    return value


def checked_paths(paths: object, count: int, role: str) -> list[str]:
    require(isinstance(paths, list) and len(paths) == count, f"{role} requires {count} paths")
    require(all(isinstance(path, str) for path in paths) and paths == sorted(set(paths)), f"unsorted or duplicate {role} paths")
    return paths


def admit(repo: Path, valence_module: Path) -> None:
    repo = repo.resolve(strict=True)
    require(repo.is_dir(), "missing repository root")
    candidate_path = safe_file(repo, CANDIDATE_PATH)
    reviewed_path = safe_file(repo, REVIEWED_PATH)
    require(blake3(candidate_path) == CANDIDATE_B3, "independently reviewed candidate snapshot drift")
    require(blake3(reviewed_path) == REVIEWED_B3, "independently reviewed approval binding drift")
    candidate = json_file(candidate_path)
    reviewed = json_file(reviewed_path)
    require(candidate.get("status") == "PENDING" and candidate.get("selected_for_named_rails") is False, "historical candidate was rebound")
    require(candidate.get("independent_owner_approval") is None, "historical candidate approval was rewritten")
    require(reviewed.get("schema") == "octet.function-object-v2-reviewed-source-manifest.v1", "unsupported reviewed schema")
    require(reviewed.get("approval_status") == "REVIEWED_SOURCE_AND_REFERENCES", "missing reviewed approval status")
    require(reviewed.get("candidate_manifest") == {"path": CANDIDATE_PATH, "blake3": CANDIDATE_B3}, "wrong candidate binding")
    approval = reviewed.get("approval")
    require(isinstance(approval, dict) and approval.get("owner_reply") == "approve", "missing scoped owner approval")
    require(approval.get("evidence_path") == APPROVAL_MANIFEST_PATH, "wrong approval reference")
    require("excludes future consumer-test code" in approval.get("scope", ""), "approval scope overclaims tests")
    historical_approval = repo / APPROVAL_MANIFEST_PATH
    require(not historical_approval.exists() and not historical_approval.is_symlink(), "historical active approval path was resurrected")
    approval_file = safe_file(repo, APPROVAL_ARCHIVE_PATH)
    require(blake3(approval_file) == APPROVAL_ARCHIVE_B3, "archived approval byte drift")
    approval_text = approval_file.read_text()
    require("replied `approve`" in approval_text and "NOT a claim" in approval_text, "approval reference missing bounded decision")

    for name in ("normalization_algorithm", "tested_octet_version", "source_selections", "source_file_hashes", "reference_hashes"):
        require(reviewed.get(name) == candidate.get(name), f"reviewed {name} differs from frozen candidate")
    require(reviewed.get("normalization_algorithm") == "octet-source-token-v2", "wrong normalization algorithm")
    require(reviewed.get("tested_octet_version") == "0.1.0", "wrong Octet version")
    require(reviewed.get("reviewed_octet_modules") == candidate.get("prospective_octet_modules"), "Octet module binding drift")
    valence = reviewed.get("reviewed_valence_module")
    require(isinstance(valence, dict) and valence == {
        "repository_uri": "https://github.com/OnixResearch/valence.git",
        "path": MODULE_PATH,
        "blake3": MODULE_B3,
        "revision": REVISION,
    }, "wrong reviewed Valence module/revision")
    require(candidate.get("tested_valence_module", {}).get("blake3") == MODULE_B3, "candidate Valence module drift")
    require(blake3(valence_module.resolve(strict=True)) == MODULE_B3, "selected upstream Valence module bytes drift")

    selections = reviewed["source_selections"]
    require(set(selections) == {"fixed_quoted_url", "internal_corpus", "expanded_internal_corpus"}, "unexpected selection role")
    fixed = checked_paths(selections["fixed_quoted_url"], 1, "fixed")
    internal = checked_paths(selections["internal_corpus"], 18, "internal")
    expanded = checked_paths(selections["expanded_internal_corpus"], 36, "expanded")
    require(set(internal).issubset(expanded), "expanded selection lost internal sources")
    union = sorted(set(fixed + internal + expanded))
    require(len(union) == 37, "selected source union must contain exactly 37 paths")
    hashes = reviewed["source_file_hashes"]
    require(isinstance(hashes, list) and [row.get("path") for row in hashes] == union, "source hash paths do not match selected union")
    for row in hashes:
        require(blake3(safe_file(repo, row["path"])) == row.get("blake3"), f"selected source byte drift: {row['path']}")
    for row in reviewed["reviewed_octet_modules"]:
        require(blake3(safe_file(repo, row["path"])) == row["blake3"], f"selected Octet module drift: {row['path']}")

    references = reviewed["reference_hashes"]
    require(isinstance(references, list) and len(references) == 4, "four independent references required")
    reference_paths = [row.get("path") for row in references]
    require(reference_paths == sorted(set(reference_paths)), "unsorted or duplicate reference paths")
    require({path.rsplit("/", 1)[-1] for path in reference_paths} == set(REFERENCE_FILES), "unexpected reference selection")
    require(sorted(row.get("object_count") for row in references) == REFERENCE_COUNTS, "reviewed reference counts drift")
    for row in references:
        path = safe_file(repo, row["path"])
        require(blake3(path) == row["blake3"], f"saved reference byte drift: {row['path']}")
        document = json_file(path)
        role = REFERENCE_FILES[path.name]
        expected_paths = ["src/lib.rs"] if role == "fixed_quoted_url" else selections[role]
        require(document.get("source_paths") == expected_paths, f"unexpected {role} receipt source selection")
        require(document.get("object_count") == row["object_count"], f"saved reference object count drift: {row['path']}")
        boundary = document.get("boundary")
        require(isinstance(boundary, dict) and boundary.get("claims_correctness") is False and boundary.get("claims_semantic_equivalence") is False, f"false-boundary violation: {row['path']}")
        if path.name.endswith("caveat-taxonomy.json"):
            buckets = document.get("source_buckets")
            require(isinstance(buckets, list) and [bucket.get("source_path") for bucket in buckets] == expanded, "taxonomy source buckets drift")
            require(sum(bucket.get("object_count", 0) for bucket in buckets) == row["object_count"], "taxonomy bucket count drift")
        else:
            require(document.get("schema") == "octet.function-object-corpus-receipt.v1" and document.get("mode") == "corpus-receipt", "wrong reference receipt shape")

    cargo = tomllib.loads(safe_file(repo, "cargo-octet/Cargo.toml").read_text())
    require(cargo["package"]["version"] == reviewed["tested_octet_version"], "current Octet version drift")
    require(cargo["dependencies"]["valence-core"] == {"git": GIT_URL, "rev": REVISION, "package": "valence-core"}, "selected Cargo dependency drift")
    lock = tomllib.loads(safe_file(repo, "Cargo.lock").read_text())
    packages = [package for package in lock["package"] if package["name"] == "valence-core"]
    require(len(packages) == 1 and packages[0].get("source") == CARGO_SOURCE, "Cargo.lock selected Valence drift")
    nix_lock = json_file(safe_file(repo, "flake.lock"))["nodes"]["valence"]
    expected_original = {"type": "git", "url": GIT_URL, "rev": REVISION, "ref": REVIEW_REF}
    locked = nix_lock["locked"]
    require(nix_lock["original"] == expected_original, "Nix original Valence input drift")
    require(all(locked.get(key) == value for key, value in expected_original.items()) and locked.get("narHash") == NIX_NAR_HASH, "Nix locked Valence revision or NAR drift")
    flake = safe_file(repo, "flake.nix").read_text()
    require(len(re.findall(r"valence\s*=\s*\{\s*url\s*=\s*\"" + re.escape(FLAKE_URL) + r"\";", flake)) == 1, "selected flake Valence input drift")
    cutover = json_file(safe_file(repo, "standards/valence-core-cutover/generated-manifest.json"))
    require(cutover["standalone_source"]["cargo_source"] == CARGO_SOURCE and cutover["standalone_source"]["revision"] == REVISION, "generated Valence cutover pin drift")
    modules = [module for module in cutover["modules"] if module["module_or_schema"] == "function_object"]
    require(len(modules) == 1 and modules[0]["standalone_source_b3"] == "b3:" + MODULE_B3, "generated Valence module binding drift")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--valence-module", required=True, type=Path)
    args = parser.parse_args()
    try:
        admit(args.repo, args.valence_module)
    except (AdmissionError, KeyError, TypeError, ValueError, OSError) as error:
        print(f"reviewed-v2-source: REJECT {error}", file=sys.stderr)
        return 1
    print("reviewed-v2-source: ADMITTED independently bound source and references (not a correctness or owner-signature proof)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
